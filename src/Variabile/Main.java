package Variabile;

public class Main {
    static void main(String[] args) {

        //date primitive

        //byte
        byte byteNumber = 12; // -127 <-> 128
        System.out.println(byteNumber);

        //short
        short shortNumber = 12989; // -32.768 <-> 32.767
        System.out.println(shortNumber);

        //int
        int intNumber = 981313; // --2.147.483.648 <-> 2.147.483.647
        System.out.println(intNumber);

        //long
        long longNumber = 1321312312; // miliarde
        System.out.println(longNumber);

        //float
        float floatNumber = 30.4323f;// numar
        System.out.println(floatNumber);

        //double
        double doubleNumber = 30.21;
        System.out.println(doubleNumber);

        //character
        char character = 'a';
        System.out.println(character);

        //bool
        boolean firstBoolean = false;
        System.out.println(firstBoolean);






    }
}
